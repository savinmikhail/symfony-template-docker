#!/usr/bin/env bash
# Deploy a CI-verified tag to a recovered Compose installation without Git metadata.
set -euo pipefail
root=${1:?deployment root}; tag=${2:?release tag}; revision=${3:?commit SHA}; archive=${4:?source archive}; project=${5:?Compose project}; images=${6:?JSON image mapping}; shift 6
services=("$@")
[[ "$root" = /* && "$root" != / && "$root" != *..* ]] || exit 64
[[ "$tag" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ && "$revision" =~ ^[0-9a-f]{40}$ && "$project" =~ ^[a-zA-Z0-9_-]+$ && ${#services[@]} -gt 0 ]] || exit 64
for service in "${services[@]}"; do [[ "$service" =~ ^[a-zA-Z0-9_-]+$ ]] || exit 64; done
stage="$root/.releases/$revision"
[[ ! -e "$stage" ]] || { echo 'Release directory already exists; inspect the previous attempt before retrying.' >&2; exit 1; }
install -d -m 0700 "$stage"
# Archive is generated by git archive for the validated tag, never from a dirty checkout.
tar -xzf "$archive" -C "$stage"
for file in .env.local app/.env.local docker-compose.recovery.yml; do
 if [[ -f "$root/$file" ]]; then install -d "$(dirname "$stage/$file")"; cp -p "$root/$file" "$stage/$file"; fi
done
python3 - "$stage" "$revision" "$images" "${services[@]}" <<'PY'
import json,re,sys
from pathlib import Path
stage=Path(sys.argv[1]); revision=sys.argv[2]; images=json.loads(sys.argv[3]); requested=sys.argv[4:]
if not images or not all(isinstance(v,str) and v.endswith(':'+revision) for v in images.values()): raise SystemExit('Images must be bound to the verified revision')
defined=set()
for name in ['docker-compose.yml','docker-compose.prod.yml','docker-compose.recovery.yml']:
 path=stage/name
 if path.exists(): defined.update(re.findall(r'^  ([a-zA-Z0-9_-]+):',path.read_text(),re.M))
images={name:image for name,image in images.items() if name in defined}
settings={'services':{name:{'image':image,'environment':{'APP_VERSION':revision}} for name,image in images.items()}}
(stage/'docker-compose.tag.json').write_text(json.dumps(settings))
(stage/'deployment-services.txt').write_text('\n'.join(s for s in requested if s in defined)+'\n')
PY
compose=(docker compose --project-name "$project" --project-directory "$stage" --env-file "$stage/.env")
[[ ! -f "$stage/.env.local" ]] || compose+=(--env-file "$stage/.env.local")
compose+=(-f "$stage/docker-compose.yml")
[[ ! -f "$stage/docker-compose.prod.yml" ]] || compose+=(-f "$stage/docker-compose.prod.yml")
[[ ! -f "$stage/docker-compose.recovery.yml" ]] || compose+=(-f "$stage/docker-compose.recovery.yml")
compose+=(-f "$stage/docker-compose.tag.json")
services=(); while IFS= read -r service; do services+=("$service"); done < "$stage/deployment-services.txt"
"${compose[@]}" config --quiet
if [[ "${SNAPSHOT_START_DB:-0}" = 1 ]]; then "${compose[@]}" up -d --wait db; fi
"${compose[@]}" pull "${services[@]}"
images=$(python3 -c 'import json,sys; print(json.dumps({k:v["image"] for k,v in json.load(open(sys.argv[1]))["services"].items()}))' "$stage/docker-compose.tag.json")
python3 - "$images" "$revision" <<'PY'
import json,subprocess,sys
for image in set(json.loads(sys.argv[1]).values()):
 label=subprocess.check_output(['docker','image','inspect',image,'--format','{{index .Config.Labels "org.opencontainers.image.revision"}}'],text=True).strip()
 if label!=sys.argv[2]: raise SystemExit('Image revision mismatch')
PY
# Keep immutable image IDs and the previous source/configuration for rollback.
python3 - "$stage" "$project" "${services[@]}" <<'PY'
import json,subprocess,sys
from pathlib import Path
services={}; project=sys.argv[2]
for service in sys.argv[3:]:
 ids=subprocess.check_output(['docker','ps','-aq','--filter','label=com.docker.compose.project='+project,'--filter','label=com.docker.compose.service='+service],text=True).split()
 if ids:
  image=subprocess.check_output(['docker','inspect',ids[0],'--format','{{.Image}}'],text=True).strip()
  services[service]={'image':image}
Path(sys.argv[1]+'/rollback-images.json').write_text(json.dumps({'services':services}))
PY
previous=$(readlink "$root/.current-release" || true)
rollback() {
 local code=$?
 trap - ERR
 echo 'Release failed; restoring previous application images (database is not rolled back).' >&2
 if [[ -n "$previous" ]]; then
  # Each successful release retains its full resolved configuration and private env.
  bash "$previous/scripts/snapshot-restart.sh" || true
 else
  old_services=(); while IFS= read -r service; do old_services+=("$service"); done < <(python3 -c 'import json,sys; print("\n".join(json.load(open(sys.argv[1]))["services"]))' "$stage/rollback-images.json")
  "${compose[@]}" stop "${services[@]}" || true
  if (( ${#old_services[@]} )); then "${compose[@]}" -f "$stage/rollback-images.json" up -d --no-deps --no-build --pull never "${old_services[@]}" || true; fi
 fi
 exit "$code"
}
trap rollback ERR
php_service=${SNAPSHOT_PHP_SERVICE:-php}
[[ "$php_service" =~ ^[a-zA-Z0-9_-]+$ ]] || exit 64
"${compose[@]}" run --rm --no-deps "$php_service" php bin/console doctrine:migrations:migrate --env=prod --no-debug --no-interaction
"${compose[@]}" up -d --no-deps --no-build --pull never --wait --wait-timeout 120 "${services[@]}"
"${compose[@]}" exec -T "${SNAPSHOT_SMOKE_SERVICE:-nginx}" wget -q -O /dev/null "${SNAPSHOT_SMOKE_URL:-http://127.0.0.1:8081/metrics}"
# Save an exact restart command without embedding credentials.
install -d "$stage/scripts"
{ printf '#!/usr/bin/env bash\nset -euo pipefail\n'; printf '%q ' "${compose[@]}" up -d --no-deps --no-build --pull never --wait --wait-timeout 120 "${services[@]}"; printf '\n'; } > "$stage/scripts/snapshot-restart.sh"
chmod 0700 "$stage/scripts/snapshot-restart.sh"
printf '{"tag":"%s","revision":"%s"}\n' "$tag" "$revision" > "$stage/release.json"
ln -s "$stage" "$root/.current-release.next"
python3 - "$root" <<'PYLINK'
import os,sys
os.replace(sys.argv[1]+'/.current-release.next',sys.argv[1]+'/.current-release')
PYLINK
trap - ERR
echo "Released $tag ($revision)"
